import React, { useState } from 'react';
import { X, Copy, Check, Printer, FileText } from 'lucide-react';
import { DecisionResult } from '../types/decision';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  decision: DecisionResult;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  decision,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  // Build markdown representation
  const generateMarkdown = () => {
    return `# The Tiebreaker Decision Report
**Decision Dilemma:** ${decision.decisionTitle}
**Date:** ${new Date(decision.createdAt).toLocaleDateString()}
**Analytical Lens:** ${decision.advisorLens}
**Key Priorities:** ${decision.priorities.join(', ')}

---

## Executive Recommendation
* **Recommended Choice:** ${decision.recommendation.recommendedOption} (${decision.recommendation.confidencePercentage}% Confidence)
* **Verdict:** "${decision.recommendation.verdict}"
* **Core Tradeoff:** ${decision.recommendation.keyTradeoff}
* **Immediate 24-Hour Next Step:** ${decision.recommendation.immediateNextStep}

### Summary
${decision.executiveSummary}

---

## Options Evaluated
${decision.options
  .map(
    (opt) => `### ${opt.optionName}
*Tagline:* ${opt.tagline}
*Best if:* ${opt.bestIf}

**Top Pros:**
${opt.pros.map((p) => `- [${p.impact} Impact] **${p.title}** (${p.category}): ${p.description}`).join('\n')}

**Top Cons:**
${opt.cons.map((c) => `- [${c.impact} Impact] **${c.title}** (${c.category}): ${c.description}`).join('\n')}

**SWOT Snapshot:**
* Strengths: ${opt.swot.strengths.slice(0, 3).join('; ')}
* Weaknesses: ${opt.swot.weaknesses.slice(0, 3).join('; ')}
* Opportunities: ${opt.swot.opportunities.slice(0, 3).join('; ')}
* Threats: ${opt.swot.threats.slice(0, 3).join('; ')}
`
  )
  .join('\n\n')}

---

## The 10/10/10 Rule
* **In 10 Minutes:** ${decision.tenTenTenRule.tenMinutes}
* **In 10 Months:** ${decision.tenTenTenRule.tenMonths}
* **In 10 Years:** ${decision.tenTenTenRule.tenYears}

---

## Worst-Case Stress Test
${decision.worstCaseStressTest
  .map(
    (w) => `* **${w.optionName}** (${w.reversibility}): ${w.worstCase}
  * Mitigation: ${w.mitigationStrategy}`
  )
  .join('\n')}

---
*Generated by The Tiebreaker - AI Decision Intelligence*
`;
  };

  const markdownContent = generateMarkdown();

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(markdownContent);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (e) {
      console.error('Failed to copy', e);
    }
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/60 p-4 backdrop-blur-xs animate-in fade-in">
      <div className="flex max-h-[85vh] w-full max-w-2xl flex-col rounded-2xl border border-slate-200 bg-white shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-slate-200 px-6 py-4">
          <div className="flex items-center gap-2">
            <FileText className="h-5 w-5 text-indigo-600" />
            <h3 className="text-base font-bold text-slate-900">
              Export Decision Memo
            </h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-100 hover:text-slate-700 transition-colors"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Content Preview */}
        <div className="flex-1 overflow-y-auto p-6 bg-slate-50">
          <pre className="rounded-xl border border-slate-200 bg-white p-4 text-[11px] font-mono text-slate-800 whitespace-pre-wrap leading-relaxed">
            {markdownContent}
          </pre>
        </div>

        {/* Footer actions */}
        <div className="flex items-center justify-between border-t border-slate-200 bg-white px-6 py-4">
          <button
            type="button"
            onClick={handlePrint}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-200 px-3.5 py-2 text-xs font-semibold text-slate-700 hover:bg-slate-50 transition-colors"
          >
            <Printer className="h-4 w-4" />
            <span>Print / Save PDF</span>
          </button>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={onClose}
              className="rounded-lg px-3.5 py-2 text-xs font-semibold text-slate-600 hover:bg-slate-100 transition-colors"
            >
              Close
            </button>
            <button
              type="button"
              onClick={handleCopy}
              className="inline-flex items-center gap-1.5 rounded-lg bg-indigo-600 px-4 py-2 text-xs font-bold text-white shadow-xs hover:bg-indigo-700 active:scale-95 transition-all"
            >
              {copied ? <Check className="h-4 w-4" /> : <Copy className="h-4 w-4" />}
              <span>{copied ? 'Copied to Clipboard!' : 'Copy Markdown'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
